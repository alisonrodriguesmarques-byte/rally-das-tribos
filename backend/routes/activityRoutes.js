'use strict';
const express=require('express');
module.exports=(missions,exams,auth)=>{
 const router=express.Router();
 router.use(auth.requireSession,auth.requireCsrf);
 const run=fn=>async(req,res,next)=>{try{res.json({success:true,data:await fn(req)});}catch(error){next(error);}};
 const actor=req=>req.auth.user.id;
 router.get('/edicoes',run(req=>missions.editions(actor(req))));
 router.get('/vinculos',run(req=>missions.accounts(actor(req))));
 router.post('/vinculos',run(req=>missions.linkAccount(actor(req),req.body)));
 router.get('/missoes/edicao/:rally',run(req=>missions.list(actor(req),req.params.rally)));
 router.post('/missoes/edicao/:rally',run(req=>missions.save(actor(req),req.params.rally,req.body)));
 router.put('/missoes/edicao/:rally/:id',run(req=>missions.save(actor(req),req.params.rally,req.body,req.params.id)));
 router.post('/missoes/:id/publicar',run(req=>missions.publish(actor(req),req.params.id)));
 router.post('/missoes/:id/encerrar',run(req=>missions.publish(actor(req),req.params.id,true)));
 router.post('/missoes/:id/entregas',run(req=>missions.deliver(actor(req),req.params.id,req.body)));
 router.post('/entregas/:id/revisar',run(req=>missions.review(actor(req),req.params.id,req.body)));
 router.get('/provas/edicao/:rally',run(req=>exams.list(actor(req),req.params.rally)));
 router.post('/provas/edicao/:rally',run(req=>exams.save(actor(req),req.params.rally,req.body)));
 router.put('/provas/edicao/:rally/:id',run(req=>exams.save(actor(req),req.params.rally,req.body,req.params.id)));
 router.post('/provas/:id/publicar',run(req=>exams.publish(actor(req),req.params.id)));
 router.post('/provas/:id/encerrar',run(req=>exams.publish(actor(req),req.params.id,true)));
 router.put('/provas/:id/representantes',run(req=>exams.representatives(actor(req),req.params.id,req.body)));
 router.post('/provas/:id/iniciar',run(req=>exams.start(actor(req),req.params.id)));
 router.post('/tentativas/:id/respostas',run(req=>exams.finish(actor(req),req.params.id,req.body)));
 return router;
};
